const hdr = (c: THREE.Color, k: number) => new THREE.MeshBasicMaterial({ color: c.clone().multiplyScalar(k), toneMapped: false });

/** Dải dữ liệu dọc: các khối "mã" cuộn lên (theo toạ độ thế giới, không cần UV) */
function dataMaterial(color: THREE.Color) {
  return new THREE.ShaderMaterial({
    uniforms: { uT: ROOM_U.uT, uTravel: ROOM_U.uTravel, uC: { value: color.clone().multiplyScalar(2.4) } },
    vertexShader: "varying vec3 vP; void main(){ vP = position; gl_Position = projectionMatrix * modelViewMatrix * vec4(position,1.0); }",
    fragmentShader: `uniform float uT; uniform float uTravel; uniform vec3 uC; varying vec3 vP;
      float h(vec2 p){ return fract(sin(dot(p, vec2(41.3, 289.1))) * 43758.5); }
      void main(){
        float col = floor(atan(vP.x, vP.z) * 120.0);
        float row = floor(vP.y * 9.0 - uT * (1.5 + h(vec2(col, 1.0)) * 2.0 + uTravel * 12.0));
        float on = step(0.45, h(vec2(col, row)));
        float head = step(0.94, h(vec2(col, row + 7.0)));
        vec3 c = uC * (0.18 + on * 0.55 + head * 1.4);
        gl_FragColor = vec4(c, 1.0);
      }`,
    toneMapped: false,
  });
}
/** Băng Turing: 256 ô nhớ quanh chân mái, đầu đọc chạy vòng, ô đổi bit khi đầu đọc đi qua */
function tapeMaterial() {
  return new THREE.ShaderMaterial({
    uniforms: { uT: ROOM_U.uT, uTravel: ROOM_U.uTravel },
    vertexShader: "varying vec3 vP; void main(){ vP = position; gl_Position = projectionMatrix * modelViewMatrix * vec4(position,1.0); }",
    fragmentShader: `uniform float uT; uniform float uTravel; varying vec3 vP;
      float h(float x){ return fract(sin(x * 91.7) * 43758.5); }
      void main(){
        float a = atan(vP.x, -vP.z) / 6.2831853 + 0.5;          // 0..1 quanh vòng
        float cell = floor(a * 256.0);
        float f = fract(a * 256.0);
        float head = fract(uT * (0.02 + uTravel * 0.2));
        float hc = floor(head * 256.0);
        float passes = floor(uT * (0.02 + uTravel * 0.2));
        float bit = step(0.5, h(cell + (cell < hc ? passes + 1.0 : passes) * 17.0));
        float v = fract(vP.y * 2.0 + 0.0);
        float frame = step(0.08, f) * step(f, 0.92) * step(0.12, v) * step(v, 0.88);
        vec3 c0 = vec3(0.12, 0.09, 0.2); vec3 c1 = vec3(1.0, 0.72, 0.28) * 2.2;
        vec3 c = mix(c0, mix(c0 * 2.0, c1, bit), frame);
        float isHead = step(abs(cell - hc), 0.5);
        c = mix(c, vec3(0.3, 1.0, 1.2) * 3.0, isHead * frame);
        gl_FragColor = vec4(c, 1.0);
      }`,
    toneMapped: false,
  });
}
/** Cáp năng lượng: xung sáng chạy từ bàn điều khiển ra tường */
function pulseMaterial(color: THREE.Color) {
  return new THREE.ShaderMaterial({
    uniforms: { uT: ROOM_U.uT, uTravel: ROOM_U.uTravel, uC: { value: color.clone() } },
    vertexShader: "varying vec3 vP; void main(){ vP = position; gl_Position = projectionMatrix * modelViewMatrix * vec4(position,1.0); }",
    fragmentShader: `uniform float uT; uniform float uTravel; uniform vec3 uC; varying vec3 vP;
      void main(){
        float r = length(vP.xz);
        float p = fract(r * 0.18 - uT * (0.45 + uTravel * 2.5));
        float pulse = smoothstep(0.0, 0.05, p) * (1.0 - smoothstep(0.05, 0.3, p));
        gl_FragColor = vec4(uC * (0.5 + pulse * 3.5 + uTravel), 1.0);
      }`,
    toneMapped: false,
  });
}
/** Kính (lan can, sàn cầu): trong suốt, vạch quét ngang kiểu hologram */
function glassMaterial() {
  return new THREE.ShaderMaterial({
    uniforms: { uT: ROOM_U.uT },
    vertexShader: "varying vec3 vP; void main(){ vP = position; gl_Position = projectionMatrix * modelViewMatrix * vec4(position,1.0); }",
    fragmentShader: `uniform float uT; varying vec3 vP;
      void main(){
        float scan = 0.5 + 0.5 * sin(vP.y * 60.0 - uT * 3.0);
        float sweep = smoothstep(0.92, 1.0, sin(atan(vP.x, vP.z) * 2.0 - uT * 0.7));
        vec3 c = vec3(0.35, 0.85, 1.0) * (0.10 + scan * 0.05 + sweep * 0.35);
        gl_FragColor = vec4(c, 0.16 + sweep * 0.2);
      }`,
    transparent: true,
    depthWrite: false,
    side: THREE.DoubleSide,
    blending: THREE.AdditiveBlending,
  });
}

/** Chuyển cảnh GLB → vật liệu game (dùng chung theo tên vật liệu; bộ chương trình cố định) */
function useRoomScene() {
  const gltf = useGLTF(ROOM_GLB);
  return useMemo(() => {
    const cache = new Map<string, THREE.Material>();
    const special = {
      data: dataMaterial(new THREE.Color("#39f3ff")),
      tape: tapeMaterial(),
      pulse: pulseMaterial(new THREE.Color("#39f3ff")),
      glass: glassMaterial(),
    };
    const conv = (mesh: THREE.Mesh, src: THREE.Material) => {
      const std = src as THREE.MeshStandardMaterial;
      const n = std.name;
      if (mesh.name.startsWith("tess_cable_glow")) return special.pulse;
      if (n === "glow_data") return special.data;
      if (n === "glow_tape") return special.tape;
      if (n.startsWith("glass_")) return special.glass;
      const key = n;
      let m = cache.get(key);
      if (!m) {
        if (n.startsWith("glow_")) m = hdr(std.color, n === "glow_gold" || n === "glow_amber" ? 2.0 : 2.4);
        else m = bakedMaterial(std, ROOM_U);
        cache.set(key, m);
      }
      return m;
    };
    const scene = gltf.scene.clone(true);
    scene.traverse((o) => {
      const mesh = o as THREE.Mesh;
      if (!mesh.isMesh) return;
      mesh.material = Array.isArray(mesh.material) ? mesh.material.map((x) => conv(mesh, x)) : conv(mesh, mesh.material);
      if (mesh.name.startsWith("glass") || (mesh.material as THREE.Material).transparent) mesh.renderOrder = 4;
    });
    return { scene, mats: [...cache.values(), ...Object.values(special)] };
  }, [gltf]);
}

// ───────── Lỗ sáng phyllotaxis (instanced) ─────────
const APS = apertures();
function Apertures() {
  const discs = useRef<THREE.InstancedMesh>(null);
  const rings = useRef<THREE.InstancedMesh>(null);
  const { discGeo, ringGeo, discMat, ringMat } = useMemo(() => {
    const discGeo = new THREE.CircleGeometry(0.26, 20);
    const ks = new Float32Array(APS.map((a) => a.k));
    const ds = new Float32Array(APS.map((a) => (a.dome ? 1 : 0)));
    discGeo.setAttribute("aK", new THREE.InstancedBufferAttribute(ks, 1));
    discGeo.setAttribute("aDome", new THREE.InstancedBufferAttribute(ds, 1));
    // Vành đồng phẳng (32 tam giác) thay vì xuyến (240) — ở khoảng cách này nhìn như nhau, nhẹ hơn 7 lần
    const ringGeo = new THREE.RingGeometry(0.255, 0.32, 16, 1);
    const discMat = new THREE.ShaderMaterial({
      uniforms: { uT: ROOM_U.uT, uTravel: ROOM_U.uTravel },
      vertexShader: `attribute float aK; attribute float aDome; varying float vK; varying float vDome; varying vec2 vUv;
        void main(){ vK = aK; vDome = aDome; vUv = uv; gl_Position = projectionMatrix * modelViewMatrix * instanceMatrix * vec4(position, 1.0); }`,
      fragmentShader: `uniform float uT; uniform float uTravel; varying float vK; varying float vDome; varying vec2 vUv;
        void main(){
          float r = length(vUv - 0.5) * 2.0;
          // sóng thở chạy dọc chỉ số góc vàng; khi du hành: quét nhanh nhiều màu
          // sóng chạy theo chỉ số n (xoắn ốc Fibonacci hiện ra như các cánh tay xoắn) + nhấp nháy hiếm
          float idle = pow(0.5 + 0.5 * sin(uT * 0.9 - vK * 48.0), 6.0);
          float tw = step(0.985, fract(sin(floor(uT * 2.0) * 13.1 + vK * 977.0) * 4375.5));
          float sweep = smoothstep(0.85, 1.0, fract(vK * 3.0 - uT * 1.6));
          float w = mix(0.1 + 0.9 * idle + tw * 0.8, 0.3 + 1.7 * sweep, uTravel);
          float hue = fract(vK * 7.0 * 1.618034);
          vec3 cyan = vec3(0.22, 0.95, 1.0), gold = vec3(1.0, 0.74, 0.3), mag = vec3(1.0, 0.25, 0.7);
          vec3 c = hue < 0.62 ? cyan : (hue < 0.9 ? gold : mag);
          c = mix(c, vec3(0.75, 0.8, 1.0), vDome * 0.35);
          float core = 1.0 - smoothstep(0.0, 0.85, r);
          float rim = smoothstep(0.72, 0.8, r) * (1.0 - smoothstep(0.86, 0.96, r));
          vec3 col = c * (core * 1.6 + 0.12) * w * 2.0 + c * rim * 0.35;
          gl_FragColor = vec4(col * (1.0 - smoothstep(0.96, 1.0, r)), 1.0);
        }`,
      toneMapped: false,
    });
    const ringMat = new THREE.MeshBasicMaterial({ color: new THREE.Color("#a07a3e"), side: THREE.DoubleSide });
    return { discGeo, ringGeo, discMat, ringMat };
  }, []);
  useEffect(() => () => [discGeo, ringGeo, discMat, ringMat].forEach((x) => x.dispose()), [discGeo, ringGeo, discMat, ringMat]);
  useEffect(() => {
    const m = new THREE.Matrix4();
    const q = new THREE.Quaternion();
    const z = new THREE.Vector3(0, 0, 1);
    APS.forEach((a, i) => {
      q.setFromUnitVectors(z, new THREE.Vector3(a.nx, a.ny, a.nz));
      const s = a.dome ? 1.15 : 1.0;
      m.compose(new THREE.Vector3(a.x, a.y, a.z), q, new THREE.Vector3(s, s, s));
      discs.current?.setMatrixAt(i, m);
      rings.current?.setMatrixAt(i, m);
    });
    if (discs.current) discs.current.instanceMatrix.needsUpdate = true;
    if (rings.current) rings.current.instanceMatrix.needsUpdate = true;
  }, [discGeo, ringGeo, discMat, ringMat]);
  return (
    <group>
      <instancedMesh ref={discs} args={[discGeo, discMat, APS.length]} frustumCulled={false} />
      <instancedMesh ref={rings} args={[ringGeo, ringMat, APS.length]} frustumCulled={false} />
    </group>
  );
}

// ───────── Sàn Penrose P3 (Robinson triangles, deflation) ─────────
type Tri = [number, [number, number], [number, number], [number, number]];
function penrose(radius: number, depth: number) {
  let tris: Tri[] = [];
  for (let i = 0; i < 10; i++) {
    let B: [number, number] = [Math.cos(((2 * i - 1) * Math.PI) / 10) * radius, Math.sin(((2 * i - 1) * Math.PI) / 10) * radius];
    let C: [number, number] = [Math.cos(((2 * i + 1) * Math.PI) / 10) * radius, Math.sin(((2 * i + 1) * Math.PI) / 10) * radius];
    if (i % 2 === 0) [B, C] = [C, B];
    tris.push([0, [0, 0], B, C]);
  }
  const lerp = (a: [number, number], b: [number, number], t: number): [number, number] => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
  for (let d = 0; d < depth; d++) {
    const out: Tri[] = [];
    for (const [c, A, B, C] of tris) {
      if (c === 0) {
        const P = lerp(A, B, 1 / PHI);
        out.push([0, C, P, B], [1, P, C, A]);
      } else {
        const Q = lerp(B, A, 1 / PHI);
        const R = lerp(B, C, 1 / PHI);
        out.push([1, R, C, A], [1, Q, R, B], [0, R, Q, A]);
      }
    }
    tris = out;
  }
  return tris;
}
function PenroseFloor() {
  const { geo, mat } = useMemo(() => {
    const tris = penrose(17, 6).filter(([, A, B, C]) => {
      const cx = (A[0] + B[0] + C[0]) / 3;
      const cz = (A[1] + B[1] + C[1]) / 3;
      const r = Math.hypot(cx, cz);
      return r < TR.R - 0.25 && r > 4.3;
    });
    const n = tris.length * 3;
    const pos = new Float32Array(n * 3);
    const bary = new Float32Array(n * 3);
    const ctr = new Float32Array(n * 3);
    tris.forEach(([c, A, B, C], i) => {
      const mx = (B[0] + C[0]) / 2;
      const mz = (B[1] + C[1]) / 2;
      [A, B, C].forEach((p, k) => {
        pos.set([p[0], 0.012, p[1]], (i * 3 + k) * 3);
        bary.set([k === 0 ? 1 : 0, k === 1 ? 1 : 0, k === 2 ? 1 : 0], (i * 3 + k) * 3);
        ctr.set([mx, mz, c], (i * 3 + k) * 3);
      });
    });
    const geo = new THREE.BufferGeometry();
    geo.setAttribute("position", new THREE.BufferAttribute(pos, 3));
    geo.setAttribute("aBary", new THREE.BufferAttribute(bary, 3));
    geo.setAttribute("aCtr", new THREE.BufferAttribute(ctr, 3));
    const mat = new THREE.ShaderMaterial({
      uniforms: { uT: ROOM_U.uT, uPlayer: ROOM_U.uPlayer, uTravel: ROOM_U.uTravel },
      vertexShader: `attribute vec3 aBary; attribute vec3 aCtr; varying vec3 vB; varying vec3 vC; varying vec2 vXZ;
        void main(){ vB = aBary; vC = aCtr; vXZ = position.xz; gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0); }`,
      fragmentShader: `uniform float uT; uniform vec3 uPlayer; uniform float uTravel; varying vec3 vB; varying vec3 vC; varying vec2 vXZ;
        void main(){
          // cạnh của hình thoi = 2 cạnh bên của tam giác Robinson (bỏ cạnh đáy chung)
          vec3 fw = fwidth(vB);
          float e = min(vB.y / max(fw.y, 1e-4), vB.z / max(fw.z, 1e-4));
          float line = 1.0 - smoothstep(0.6, 1.8, e);
          float d = length(vC.xy - uPlayer.xz);
          float lit = (1.0 - smoothstep(0.4, 1.9, d)) * step(uPlayer.y, 0.8);
          float wave = smoothstep(0.9, 1.0, sin(length(vC.xy) * 0.9 - uT * 1.4)) * (0.25 + uTravel * 1.5);
          vec3 thick = vec3(1.0, 0.72, 0.3), thin = vec3(0.25, 0.95, 1.0);
          vec3 c = mix(thin, thick, vC.z);
          vec3 col = c * line * (0.35 + lit * 1.6 + wave) + c * (lit * 0.2 + wave * 0.12);
          gl_FragColor = vec4(col, 1.0);
        }`,
      transparent: true,
      depthWrite: false,
      blending: THREE.AdditiveBlending,
      toneMapped: false,
    });
    return { geo, mat };
  }, []);
  useEffect(() => () => [geo, mat].forEach((x) => x.dispose()), [geo, mat]);
  return <mesh geometry={geo} material={mat} renderOrder={2} frustumCulled={false} />;
}

// ───────── Hypercore: cột kính + khối lồng nhau + siêu khối 4D + cột sáng tới giếng trời ─────────
function Hypercore({ lite }: { lite?: boolean }) {
  const inner = useRef<THREE.Group>(null);
  const tess = useRef<THREE.LineSegments>(null);
  const res = useMemo(() => {
    const verts4: number[][] = [];
    for (let i = 0; i < 16; i++) verts4.push([i & 1 ? 1 : -1, i & 2 ? 1 : -1, i & 4 ? 1 : -1, i & 8 ? 1 : -1]);
    const edges: [number, number][] = [];
    for (let i = 0; i < 16; i++) for (let b = 0; b < 4; b++) if (!(i & (1 << b))) edges.push([i, i | (1 << b)]);
    const tGeo = new THREE.BufferGeometry();
    tGeo.setAttribute("position", new THREE.BufferAttribute(new Float32Array(edges.length * 6), 3));
    const line = (hex: string, k: number) => new THREE.LineBasicMaterial({ color: new THREE.Color(hex).multiplyScalar(k), toneMapped: false });
    const dodeca = new THREE.EdgesGeometry(new THREE.DodecahedronGeometry(0.42));
    const icosa = new THREE.EdgesGeometry(new THREE.IcosahedronGeometry(0.24));
    const glass = new THREE.ShaderMaterial({
      uniforms: { uT: ROOM_U.uT, uTravel: ROOM_U.uTravel },
      vertexShader: "varying vec3 vN; varying vec3 vV; varying float vY; void main(){ vec4 wp = modelMatrix * vec4(position,1.0); vN = normalize(mat3(modelMatrix) * normal); vV = normalize(cameraPosition - wp.xyz); vY = position.y; gl_Position = projectionMatrix * viewMatrix * wp; }",
      fragmentShader: `uniform float uT; uniform float uTravel; varying vec3 vN; varying vec3 vV; varying float vY;
        void main(){
          float f = pow(1.0 - abs(dot(normalize(vN), vV)), 2.5);
          float scan = smoothstep(0.7, 1.0, sin(vY * 14.0 - uT * (3.0 + uTravel * 14.0)));
          vec3 c = vec3(0.3, 0.9, 1.0) * (f * 1.6 + scan * 0.25 + 0.05) * (1.0 + uTravel * 1.5);
          gl_FragColor = vec4(c, f * 0.7 + 0.06);
        }`,
      transparent: true,
      depthWrite: false,
      blending: THREE.AdditiveBlending,
      side: THREE.DoubleSide,
      toneMapped: false,
    });
    // Cột sáng tới giếng trời: mờ ở 2 đầu, dòng nhiễu chảy lên
    const beam = new THREE.ShaderMaterial({
      uniforms: { uT: ROOM_U.uT, uTravel: ROOM_U.uTravel },
      vertexShader: "varying vec2 vUv; varying vec3 vN; varying vec3 vV; void main(){ vUv = uv; vec4 wp = modelMatrix * vec4(position,1.0); vN = normalize(mat3(modelMatrix) * normal); vV = normalize(cameraPosition - wp.xyz); gl_Position = projectionMatrix * viewMatrix * wp; }",
      fragmentShader: `uniform float uT; uniform float uTravel; varying vec2 vUv; varying vec3 vN; varying vec3 vV;
        void main(){
          float core = pow(abs(dot(normalize(vN), vV)), 1.6);
          float ends = smoothstep(0.0, 0.12, vUv.y) * (1.0 - smoothstep(0.75, 1.0, vUv.y));
          float flow = 0.6 + 0.4 * sin(vUv.y * 40.0 - uT * (4.0 + uTravel * 20.0) + sin(vUv.x * 31.4) * 2.0);
          vec3 c = vec3(0.55, 0.9, 1.0) * core * ends * flow * (0.35 + uTravel * 1.2);
          gl_FragColor = vec4(c, 1.0);
        }`,
      transparent: true,
      depthWrite: false,
      blending: THREE.AdditiveBlending,
      toneMapped: false,
    });
    return { verts4, edges, tGeo, dodeca, icosa, glass, beam, lCyan: line("#7fe3ff", 2.4), lGold: line("#ffd27a", 2.6), lVio: line("#c8a6ff", 2.6) };
  }, []);
  useEffect(
    () => () => [res.tGeo, res.dodeca, res.icosa, res.glass, res.beam, res.lCyan, res.lGold, res.lVio].forEach((x) => x.dispose()),
    [res],
  );
  useFrame(() => {
    const t = ROOM_U.uT.value;
    const k = ROOM_U.uTravel.value;
    if (inner.current) {
      inner.current.position.y = 3.0 + Math.sin(t * (1.1 + k * 5)) * (0.35 + k * 0.4);
      inner.current.rotation.y = t * (0.5 + k * 4);
      inner.current.children[0].rotation.x = t * 0.7;
      inner.current.children[1].rotation.z = -t * 1.1;
    }
    const a = t * 0.8 * (1 + k * 3);
    const c = Math.cos(a);
    const s = Math.sin(a);
    const c2 = Math.cos(a * 0.6);
    const s2 = Math.sin(a * 0.6);
    const arr = res.tGeo.attributes.position.array as Float32Array;
    const proj = (v: number[], o: number) => {
      const x = v[0] * c - v[3] * s;
      const w = v[0] * s + v[3] * c;
      const y = v[1] * c2 - v[2] * s2;
      const z = v[1] * s2 + v[2] * c2;
      const f = 0.3 / (2.6 - w);
      arr[o] = x * f;
      arr[o + 1] = y * f;
      arr[o + 2] = z * f;
    };
    res.edges.forEach(([i, j], n) => {
      proj(res.verts4[i], n * 6);
      proj(res.verts4[j], n * 6 + 3);
    });
    res.tGeo.attributes.position.needsUpdate = true;
  });
  return (
    <group>
      <mesh material={res.glass} position-y={(TR.CORE_TOP + 1.45) / 2}>
        <cylinderGeometry args={[0.55, 0.55, TR.CORE_TOP - 1.45, 32, 1, true]} />
      </mesh>
      <group ref={inner}>
        <lineSegments geometry={res.dodeca} material={res.lCyan} />
        <lineSegments geometry={res.icosa} material={res.lGold} />
        <lineSegments ref={tess} geometry={res.tGeo} material={res.lVio} />
      </group>
      {!lite && (
        <mesh material={res.beam} position-y={(5.3 + TR.HW + TR.DOME) / 2}>
          <cylinderGeometry args={[0.9, 0.7, TR.HW + TR.DOME - 5.3, 24, 1, true]} />
        </mesh>
      )}
    </group>
  );
}

// ───────── Cửa sổ lớn: HUD hologram + cửa chớp mống mắt 12 lá ─────────
function WindowHud() {
  const mats = useMemo(() => {
    const iris = new THREE.ShaderMaterial({
      uniforms: { uIris: ROOM_U.uIris, uT: ROOM_U.uT },
      vertexShader: "varying vec2 vUv; void main(){ vUv = uv; gl_Position = projectionMatrix * modelViewMatrix * vec4(position,1.0); }",
      fragmentShader: `uniform float uIris; uniform float uT; varying vec2 vUv;
        void main(){
          vec2 p = (vUv - 0.5) * 2.0; float r = length(p); float a = atan(p.y, p.x);
          if (uIris < 0.001 || r > 1.0) discard;
          // 12 lá: biên mỗi lá là đường xoắn — lỗ mở = đa giác 12 cạnh bán kính (1 − iris)
          float open = 1.05 * (1.0 - uIris);
          float sector = fract(a / 6.2831853 * 12.0 + r * 0.9 + uIris * 0.6);
          float edge = open * (1.0 + 0.1 * (sector - 0.5));
          if (r < edge) discard;
          float seam = smoothstep(0.03, 0.0, abs(sector - 0.02));
          vec3 brass = vec3(0.55, 0.4, 0.2) * (0.55 + 0.45 * sector);
          vec3 c = brass + vec3(1.0, 0.8, 0.4) * seam * 1.5 + vec3(0.3, 0.9, 1.0) * smoothstep(0.04, 0.0, r - edge) * 2.0;
          gl_FragColor = vec4(c, 1.0);
        }`,
      side: THREE.DoubleSide,
      toneMapped: false,
    });
    const hud = new THREE.ShaderMaterial({
      uniforms: { uT: ROOM_U.uT, uTravel: ROOM_U.uTravel },
      vertexShader: "varying vec2 vUv; void main(){ vUv = uv; gl_Position = projectionMatrix * modelViewMatrix * vec4(position,1.0); }",
      fragmentShader: `uniform float uT; uniform float uTravel; varying vec2 vUv;
        void main(){
          vec2 p = (vUv - 0.5) * 2.0; float r = length(p); float a = atan(p.y, p.x);
          float ring1 = smoothstep(0.006, 0.0, abs(r - 0.96));
          float ticks = step(0.9, r) * step(r, 0.95) * step(0.82, fract((a + uT * 0.05) / 6.2831853 * 72.0));
          float ring2 = smoothstep(0.004, 0.0, abs(r - 0.62)) * step(0.5, fract((a - uT * 0.12) / 6.2831853 * 6.0));
          float cross = (smoothstep(0.004, 0.0, abs(p.x)) + smoothstep(0.004, 0.0, abs(p.y))) * step(0.2, r) * step(r, 0.45);
          float dash = step(0.97, fract(a / 6.2831853 * 3.0 - uT * 0.3)) * smoothstep(0.01, 0.0, abs(r - 0.8));
          float scan = 0.85 + 0.15 * sin(vUv.y * 600.0 + uT * 8.0);
          float v = (ring1 * 0.9 + ticks * 0.5 + ring2 * 0.6 + cross * 0.45 + dash * 1.2) * scan * (1.0 + uTravel * 1.5);
          vec3 c = mix(vec3(0.25, 0.95, 1.0), vec3(1.0, 0.35, 0.75), step(0.5, fract(uT * 0.1)) * uTravel);
          gl_FragColor = vec4(c * v * 1.6, 1.0);
        }`,
      transparent: true,
      depthWrite: false,
      blending: THREE.AdditiveBlending,
      toneMapped: false,
    });
    return { iris, hud };
  }, []);
  useEffect(() => () => [mats.iris, mats.hud].forEach((x) => x.dispose()), [mats]);
  return (
    <group position={[0, TR.WIN.y, -(TR.R - 0.35)]}>
      <mesh material={mats.iris} renderOrder={1}>
        <circleGeometry args={[TR.WIN.r + 0.05, 64]} />
      </mesh>
      <mesh material={mats.hud} position-z={0.12} renderOrder={5}>
        <circleGeometry args={[TR.WIN.r - 0.1, 64]} />
      </mesh>
    </group>
  );
}

// ───────── Tia sáng thể tích giả + bụi lơ lửng ─────────
function Atmosphere() {
  const res = useMemo(() => {
    const shaft = (color: string, k: number) =>
      new THREE.ShaderMaterial({
        uniforms: { uT: ROOM_U.uT, uC: { value: new THREE.Color(color).multiplyScalar(k) } },
        vertexShader: "varying vec2 vUv; varying vec3 vN; varying vec3 vV; void main(){ vUv = uv; vec4 wp = modelMatrix * vec4(position,1.0); vN = normalize(mat3(modelMatrix) * normal); vV = normalize(cameraPosition - wp.xyz); gl_Position = projectionMatrix * viewMatrix * wp; }",
        fragmentShader: `uniform float uT; uniform vec3 uC; varying vec2 vUv; varying vec3 vN; varying vec3 vV;
          void main(){
            float soft = pow(abs(dot(normalize(vN), vV)), 2.0);
            float along = smoothstep(0.0, 0.25, vUv.y) * (1.0 - smoothstep(0.55, 1.0, vUv.y));
            float streak = 0.7 + 0.3 * sin(vUv.x * 50.0 + uT * 0.3) * sin(vUv.x * 23.0 - uT * 0.2);
            gl_FragColor = vec4(uC * soft * along * streak, 1.0);
          }`,
        transparent: true,
        depthWrite: false,
        blending: THREE.AdditiveBlending,
        side: THREE.DoubleSide,
        toneMapped: false,
      });
    const N = 420;
    const pos = new Float32Array(N * 3);
    const seed = new Float32Array(N);
    let s = 13;
    const rnd = () => ((s = (s * 16807) % 2147483647) / 2147483647);
    for (let i = 0; i < N; i++) {
      const r = Math.sqrt(rnd()) * 12.5;
      const a = rnd() * Math.PI * 2;
      pos.set([Math.cos(a) * r, 0.3 + rnd() * 15, Math.sin(a) * r], i * 3);
      seed[i] = rnd();
    }
    const dustGeo = new THREE.BufferGeometry();
    dustGeo.setAttribute("position", new THREE.BufferAttribute(pos, 3));
    dustGeo.setAttribute("aSeed", new THREE.BufferAttribute(seed, 1));
    const dustMat = new THREE.ShaderMaterial({
      uniforms: { uT: ROOM_U.uT },
      vertexShader: `attribute float aSeed; uniform float uT; varying float vA;
        void main(){
          vec3 p = position;
          p.y = mod(p.y + uT * (0.08 + aSeed * 0.12), 15.0) + 0.3;
          p.x += sin(uT * 0.3 + aSeed * 20.0) * 0.4; p.z += cos(uT * 0.27 + aSeed * 13.0) * 0.4;
          // sáng hơn trong cột sáng giữa phòng và luồng sáng cửa sổ
          float inCol = 1.0 - smoothstep(0.6, 2.2, length(p.xz));
          float inWin = (1.0 - smoothstep(3.0, 6.0, length(vec2(p.x, p.y - 6.8)))) * smoothstep(0.0, 6.0, -p.z);
          vA = (0.25 + 0.75 * max(inCol, inWin)) * (0.5 + 0.5 * sin(uT * 2.0 + aSeed * 30.0));
          vec4 mv = modelViewMatrix * vec4(p, 1.0);
          gl_PointSize = (2.0 + aSeed * 3.0) * (12.0 / -mv.z);
          gl_Position = projectionMatrix * mv;
        }`,
      fragmentShader: `varying float vA; void main(){ float d = length(gl_PointCoord - 0.5); gl_FragColor = vec4(vec3(1.0, 0.92, 0.8) * vA * (1.0 - smoothstep(0.1, 0.5, d)) * 1.4, 1.0); }`,
      transparent: true,
      depthWrite: false,
      blending: THREE.AdditiveBlending,
      toneMapped: false,
    });
    return { win: shaft("#8fb0ff", 0.22), ocu: shaft("#cfe6ff", 0.16), dustGeo, dustMat };
  }, []);
  useEffect(() => () => [res.win, res.ocu, res.dustGeo, res.dustMat].forEach((x) => x.dispose()), [res]);
  return (
    <group>
      {/* Luồng sáng từ cửa sổ đổ chéo xuống sàn trước bàn điều khiển */}
      <mesh material={res.win} position={[0, 4.4, -8.5]} rotation-x={-Math.PI / 2 + 0.38} renderOrder={6}>
        <cylinderGeometry args={[TR.WIN.r * 0.95, 3.2, 11.5, 32, 1, true]} />
      </mesh>
      {/* Cột sáng từ giếng trời */}
      <mesh material={res.ocu} position-y={(TR.HW + TR.DOME) / 2 + 2} renderOrder={6}>
        <cylinderGeometry args={[2.1, 3.6, TR.HW + TR.DOME - 4, 32, 1, true]} />
      </mesh>
      <points geometry={res.dustGeo} material={res.dustMat} frustumCulled={false} />
    </group>
  );
}

/** Cổng Thư viện Babel ở cuối hành lang phía tây: màn sáng hổ phách có lưới lục giác + "dòng chữ" trôi */
function BabelGate() {
  const mat = useMemo(
    () =>
      new THREE.ShaderMaterial({
        uniforms: { uT: ROOM_U.uT },
        vertexShader: "varying vec2 vUv; void main(){ vUv = uv; gl_Position = projectionMatrix * modelViewMatrix * vec4(position,1.0); }",
        fragmentShader: `uniform float uT; varying vec2 vUv;
          float h(vec2 p){ return fract(sin(dot(p, vec2(41.3, 289.1))) * 43758.5); }
          void main(){
            vec2 p = vUv * vec2(6.0, 9.0);
            // lưới lục giác
            vec2 r = vec2(1.0, 1.732); vec2 hh = r * 0.5;
            vec2 a = mod(p, r) - hh; vec2 b = mod(p - hh, r) - hh;
            vec2 g = dot(a, a) < dot(b, b) ? a : b;
            float hex = smoothstep(0.42, 0.47, max(abs(g.x) * 0.866 + abs(g.y) * 0.5, abs(g.y)));
            // dòng "chữ" trôi lên
            vec2 q = vec2(floor(vUv.x * 40.0), floor(vUv.y * 60.0 - uT * 3.0));
            float glyph = step(0.6, h(q)) * step(0.3, fract(vUv.y * 60.0 - uT * 3.0));
            float edge = smoothstep(0.0, 0.12, vUv.x) * smoothstep(1.0, 0.88, vUv.x) * smoothstep(0.0, 0.08, vUv.y);
            vec3 c = vec3(1.0, 0.72, 0.36) * (0.35 + hex * 0.9) + vec3(1.0, 0.9, 0.6) * glyph * 0.35;
            gl_FragColor = vec4(c * edge * 1.6, 1.0);
          }`,
        transparent: true,
        depthWrite: false,
        blending: THREE.AdditiveBlending,
        toneMapped: false,
        side: THREE.DoubleSide,
      }),
    [],
  );
  useEffect(() => () => mat.dispose(), [mat]);
  const x = -(TR.R + TR.CORR.L - 0.25);
  return (
    <group position={[x, 0, 0]} rotation-y={Math.PI / 2}>
      <mesh material={mat} position-y={1.75}>
        <planeGeometry args={[2.6, 3.5]} />
      </mesh>
      <mesh position-y={3.6}>
        <torusGeometry args={[1.4, 0.09, 8, 32, Math.PI]} />
        <meshBasicMaterial color={new THREE.Color("#c9a25a")} />
      </mesh>
      <Label3D text="Thư viện Babel · The Library of Babel" position={[0, 3.95, 0.2]} variant="small" />
    </group>
  );
}

/** Phòng điều khiển hoàn chỉnh. lite = bản nhìn qua cửa bốt (bỏ khí quyển). */
export function TessRoom({ cx, cz, lite = false }: { cx: number; cz: number; lite?: boolean }) {
  const { scene, mats } = useRoomScene();
  const gimbals = useMemo(() => [1, 2, 3].map((i) => scene.getObjectByName(`tess_gimbal_${i}`)), [scene]);
  const flying = useRef(false);
  useEffect(() => () => mats.forEach((m) => m.dispose()), [mats]);
  useEffect(
    () => () => {
      if (lite) return;
      CAM.fovKick = 0;
      CAM.dolly = 1;
    },
    [lite],
  );
  useFrame((_, dt) => {
    const now = performance.now();
    const k = travelK(now);
    // Cường độ du hành: lên nhanh, giữ, xuống
    const tv = k < 0 ? 0 : Math.min(1, k * 5, (1 - k) * 4);
    if (!lite) {
      ROOM_U.uT.value = now / 1000;
      ROOM_U.uTravel.value += (tv - ROOM_U.uTravel.value) * Math.min(1, dt * 6);
      ROOM_U.uIris.value = k < 0 ? 0 : irisAt(k);
      // "The Fold": phòng tối dần + nhuốm tím hồng, loé sáng khi cửa chớp đóng sập; dolly-zoom (FOV mở, máy quay áp sát)
      const tvs = ROOM_U.uTravel.value;
      const flash = k < 0 ? 0 : Math.max(0, 1 - Math.abs(k - 0.48) / 0.035);
      ROOM_U.uExposure.value = 1.15 * (1 - 0.42 * tvs) + flash * 1.6;
      ROOM_U.uTint.value.copy(WHITE).lerp(FOLD_TINT, tvs * 0.7);
      // chỉ điều khiển FOV khi đang du hành (để các cảnh khác — vd. Hang Platon — tự đặt FOV riêng)
      if (k >= 0) {
        const dz = Math.sin(Math.min(1, k / 0.48) * Math.PI * 0.5) * (k < 0.48 ? 1 : Math.max(0, 1 - (k - 0.48) / 0.12));
        CAM.fovKick = 26 * dz;
        CAM.dolly = Math.tan((22.5 * Math.PI) / 180) / Math.tan(((45 + CAM.fovKick) / 2) * (Math.PI / 180));
        flying.current = true;
      } else if (flying.current) {
        CAM.fovKick = 0;
        CAM.dolly = 1;
        flying.current = false;
      }
      const p = useWorld.getState().player;
      ROOM_U.uPlayer.value.set(p.x - cx, p.y, p.z - cz);
    }
    // Con quay: 1 : φ : φ² (nhanh hơn khi du hành)
    const sp = 0.25 * (1 + ROOM_U.uTravel.value * 6);
    const t = ROOM_U.uT.value;
    if (gimbals[0]) gimbals[0].rotation.set(t * sp, 0, 0.3);
    if (gimbals[1]) gimbals[1].rotation.set(0.2, t * sp * PHI, t * sp * 0.5);
    if (gimbals[2]) gimbals[2].rotation.set(t * sp * PHI * PHI, 0.4, -t * sp * 0.3);
  });
  return (
    <group position={[cx, 0, cz]}>
      <primitive object={scene} />
      <Apertures />
      <PenroseFloor />
      <Hypercore lite={lite} />
      <WindowHud />
      {!lite && <Atmosphere />}
      {!lite && <BabelGate />}
    </group>
  );
}
